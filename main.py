import random  # Импортируем модуль random для генерации случайных чисел


def main():  # Объявляем главную функцию программы
    # Исходные данные (порядковый номер, фамилия, гендер)
    starting_data = [  # Создаём список списков с начальными данными о людях
        [1, "Алексеев", "М"],  # Первый человек: номер 1, фамилия Алексеев, мужчина
        [2, "Иванова", "Ж"],  # Второй человек: номер 2, фамилия Иванова, женщина
        [3, "Антонов", "М"],  # Третий человек: номер 3, фамилия Антонов, мужчина
        [4, "Петрова", "Ж"],  # Четвёртый человек: номер 4, фамилия Петрова, женщина
        [5, "Сидоров", "М"]  # Пятый человек: номер 5, фамилия Сидоров, мужчина
    ]

    # Формируем полный массив с добавлением возраста и пенсии
    matrix = []  # Создаём пустой список, в который будем добавлять полные данные

    for row in starting_data:  # Проходим по каждой строке исходных данных
        age = random.randint(60, 85)  # Генерируем случайный возраст от 60 до 85 лет включительно
        # Если возраст больше 70 — пенсия от 10000 до 30000, иначе от 5000 до 20000
        pension = random.randint(10000, 30000) if age > 70 else random.randint(5000, 20000)
        matrix.append(row + [age, pension])  # Добавляем к исходной строке возраст и пенсию, и кладём в matrix

    print("1. Исходная матрица:")  # Выводим заголовок первой части
    # Выводим заголовки столбцов с выравниванием
    print(f"{'№':<4} {'Фамилия':<12} {'Гендер':<8} {'Возраст':<8} {'Пенсия':<8}")

    for row in matrix:  # Проходим по каждой строке полной матрицы
        # Выводим данные с выравниванием по столбцам
        print(f"{row[0]:<4} {row[1]:<12} {row[2]:<8} {row[3]:<8} {row[4]:<8}")

    # Открываем файл для записи исходной матрицы (кодировка UTF-8)
    with open(r"C:\Users\ИСП-31\Desktop\initial_matrix.txt", "w", encoding="utf-8") as f:
        # Записываем заголовки столбцов в файл
        f.write(f"{'№':<4} {'Фамилия':<12} {'Гендер':<8} {'Возраст':<8} {'Пенсия':<8}\n")
        for row in matrix:  # Проходим по каждой строке матрицы
            # Записываем данные строки в файл
            f.write(f"{row[0]:<4} {row[1]:<12} {row[2]:<8} {row[3]:<8} {row[4]:<8}\n")

    # Фильтруем людей старше 70 лет
    elderly = [row for row in matrix if row[3] > 70]  # Создаём новый список только из тех, у кого возраст > 70

    print("\n2. Люди старше 70 лет:")  # Выводим заголовок второй части (с переносом строки)
    # Выводим заголовки столбцов
    print(f"{'№':<4} {'Фамилия':<12} {'Гендер':<8} {'Возраст':<8} {'Пенсия':<8}")

    for row in elderly:  # Проходим по отфильтрованному списку
        # Выводим данные людей старше 70 лет
        print(f"{row[0]:<4} {row[1]:<12} {row[2]:<8} {row[3]:<8} {row[4]:<8}")

    # Открываем файл для записи списка пожилых людей
    with open(r"C:\Users\ИСП-31\Desktop\elderly_people.txt", "w", encoding="utf-8") as f:
        # Записываем заголовки
        f.write(f"{'№':<4} {'Фамилия':<12} {'Гендер':<8} {'Возраст':<8} {'Пенсия':<8}\n")
        for row in elderly:  # Проходим по списку пожилых
            # Записываем данные в файл
            f.write(f"{row[0]:<4} {row[1]:<12} {row[2]:<8} {row[3]:<8} {row[4]:<8}\n")

    # Считаем общую сумму выплат пенсии
    total_pension = sum(row[4] for row in elderly)  # Суммируем пенсии всех людей старше 70 лет

    # Выводим общую сумму на экран
    print(f"\nОбщая сумма выплат пенсии людям старше 70 лет: {total_pension} руб.")

    # Открываем файл для записи общей суммы пенсии
    with open(r"C:\Users\ИСП-31\Desktop\pension_total.txt", "w", encoding="utf-8") as f:
        # Записываем текст с общей суммой в файл
        f.write(f"Общая сумма выплат пенсии людям старше 70 лет: {total_pension} руб.")

main()  # Вызываем главную функцию, чтобы программа начала работу